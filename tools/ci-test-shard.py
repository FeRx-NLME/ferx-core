#!/usr/bin/env python3
"""Split the per-PR test run into balanced shards by test BINARY (#2167).

    tools/ci-test-shard.py args K N     # cargo target args for shard K of N (1-based)
    tools/ci-test-shard.py plan N       # show every shard's targets and predicted seconds
    tools/ci-test-shard.py weights LOG  # rewrite tools/ci-test-weights.txt from a CI log

`Tests + coverage (core)` used to run `cargo llvm-cov --workspace --tests`, which
executes the ~300 test binaries one after another: ~44 min of a ~56 min job. The
matrix in `ci.yml` runs the SAME command on N runners, each restricted to its share
of the binaries, and a final job uploads the N lcov files as one Codecov upload.

Why by binary and not by test (`cargo nextest --partition`): nextest runs every
test in its own process, so a `OnceLock` fixture shared by the tests of one binary
(`fit_inputs_tests.rs`, `run_covariance_inner_scope.rs`, ...) would be recomputed
per test. Splitting by binary keeps the libtest harness, and with it every test's
threading and fixture sharing, exactly as before; only the scheduling changes.

The target list comes from `cargo metadata`, not from the weights file, so a new
test file is always run: with no weight it is scheduled at DEFAULT_WEIGHT. Stale
weights only unbalance the shards; they can never drop a test. The lib and bin
unit tests of every package (`--lib --bins`) always go to shard 1, as one unit.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS = ROOT / "tools" / "ci-test-weights.txt"
# Seconds assumed for a binary the weights file does not name. Most binaries
# take a few seconds; a new heavy one is caught at the next `weights` refresh.
DEFAULT_WEIGHT = 3.0
UNIT = "<unit>"  # the `--lib --bins` unit-test bundle


def test_targets():
    """Integration-test target names across the workspace (unique, checked)."""
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--no-deps", "--format-version", "1"],
            cwd=ROOT, check=True, capture_output=True, text=True,
        ).stdout
    )
    names = [
        t["name"]
        for p in meta["packages"]
        for t in p["targets"]
        if "test" in t["kind"] and t.get("test", True)
    ]
    dups = sorted({n for n in names if names.count(n) > 1})
    if dups:
        # `--workspace --test NAME` would select the target in every package.
        sys.exit(f"ci-test-shard: test target names are not unique: {dups}")
    return sorted(names)


def load_weights():
    w = {}
    if WEIGHTS.exists():
        for line in WEIGHTS.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                secs, name = line.split()
                w[name] = float(secs)
    return w


def plan(n):
    """Longest-processing-time-first assignment; deterministic for fixed inputs."""
    w = load_weights()
    shards = [[] for _ in range(n)]
    load = [0.0] * n
    shards[0].append(UNIT)
    load[0] = w.get(UNIT, DEFAULT_WEIGHT)
    for name in sorted(test_targets(), key=lambda t: (-w.get(t, DEFAULT_WEIGHT), t)):
        k = min(range(n), key=lambda i: (load[i], i))
        shards[k].append(name)
        load[k] += w.get(name, DEFAULT_WEIGHT)
    return shards, load


def args(k, n):
    shards, _ = plan(n)
    out = []
    for name in shards[k - 1]:
        out += ["--lib", "--bins"] if name == UNIT else ["--test", name]
    return out


def weights_from_log(log):
    """`test result: ... finished in Xs` per `Running` line of a coverage-job log."""
    w = {}
    cur = None
    for line in Path(log).read_text(errors="replace").splitlines():
        line = re.sub(r"\x1b\[[0-9;]*m", "", line)
        m = re.search(r"Running (unittests )?(\S+)", line)
        if m:
            cur = UNIT if m.group(1) else Path(m.group(2)).stem
            continue
        m = re.search(r"test result: \w+\..*finished in ([\d.]+)s", line)
        if m and cur:
            w[cur] = w.get(cur, 0.0) + float(m.group(1))
            cur = None
    if UNIT not in w:
        sys.exit(f"ci-test-shard: no unit-test timings in {log}; wrong log?")
    rows = sorted(w.items(), key=lambda kv: (-kv[1], kv[0]))
    head = (
        "# Per-binary test seconds for tools/ci-test-shard.py (#2167). Generated by\n"
        "# `tools/ci-test-shard.py weights <log>` from a `Tests + coverage (core)` CI\n"
        "# log; binaries under DEFAULT_WEIGHT are omitted. Only balances the shards —\n"
        "# a stale or missing entry never drops a test.\n"
    )
    body = "".join(f"{s:.0f} {n}\n" for n, s in rows if s >= DEFAULT_WEIGHT)
    WEIGHTS.write_text(head + body)


def main(argv):
    if len(argv) == 4 and argv[1] == "args":
        k, n = int(argv[2]), int(argv[3])
        if not 1 <= k <= n:
            sys.exit(f"ci-test-shard: shard {k} is outside 1..{n}")
        print(" ".join(args(k, n)))
    elif len(argv) == 3 and argv[1] == "plan":
        shards, load = plan(int(argv[2]))
        for i, (s, l) in enumerate(zip(shards, load), 1):
            print(f"shard {i}: {l:6.0f} s, {len(s):3d} binaries: {' '.join(s[:6])} ...")
    elif len(argv) == 3 and argv[1] == "weights":
        weights_from_log(argv[2])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)

#!/usr/bin/env python3
"""Derive the #1978 evaluation arms from each fitted base stream and its .ext.

For each fixture `reset_clock_<n>` (n in ode, cat, tte), from `reset_clock_<n>.ctl` and the
fit's final row in `results/reset_clock_<n>.ext`, write two MAXEVAL=0 streams at that point:

  reset_clock_<n>_shifted.ctl  the same model on `reset_clock_<n>_shifted.csv`: period 2
                               moved past period 1 exactly as ferx's reader moves it. This is
                               the objective NONMEM would report if T/TIME kept running.
  reset_clock_<n>_control.ctl  the TIME-as-written data with the model's time term fixed at
                               0. Nothing reads the clock, so ferx and NONMEM must agree here
                               whichever clock either side uses: it pins the data, the reset
                               and the likelihood conventions, so a gap in the other arms is
                               the clock and nothing else.

The TTE arms are evaluated at eta = 0 (`$OMEGA 0 FIX`), with the written data getting an
evaluation arm of its own, `reset_clock_tte_eval.ctl`. With the eta live, ferx and NONMEM
differ by 0.12 OFV on this joint PK-TTE model even with no reset and no time term (period 2
alone, EVID=1: NONMEM 161.2155, ferx 161.0939) -- a Laplace-level gap that is not #1978's, so
the clock is measured where it is the only difference, as `pktte_tdep.ctl` does.

    python3 make_reset_clock_arms.py      # from nonmem_anchor/, after the base fits
"""

import re

# fixture -> time_theta: 1-based index of the THETA multiplying TIME; eta0: evaluate at eta = 0
FIXTURES = {
    "ode": dict(time_theta=3, eta0=False),
    "cat": dict(time_theta=2, eta0=False),
    "tte": dict(time_theta=5, eta0=True),
}


def ext_final(name):
    lines = open("results/%s.ext" % name).read().splitlines()
    hdr = None
    for line in lines:
        f = line.split()
        if f and f[0] == "ITERATION":
            hdr = f
        elif f and f[0] == "-1000000000":
            return dict(zip(hdr, f))
    raise SystemExit("no final row in results/%s.ext" % name)


def fmt(x):
    return "%.17g" % float(x)


def rewrite(src, final, time_theta, zero_time, eta0):
    out, block = [], None
    th = om = sg = 0
    for line in src.splitlines():
        m = re.match(r"^\$(\w+)", line)
        if m:
            block = m.group(1).upper()
        body = line.split(";")[0]
        if block == "THETA" and "(" in body:
            th += 1
            val = ext_final_val(final, "THETA%d" % th)
            lo, _, hi = re.search(r"\(([^)]*)\)", body).group(1).split(",")
            if zero_time and th == time_theta:
                line = "  0 FIX            ; time term zeroed (control arm)"
            else:
                line = "  (%s, %s, %s) ; %s" % (lo.strip(), fmt(val), hi.strip(),
                                             line.split(";", 1)[1].strip())
        elif block == "OMEGA" and line.startswith("$OMEGA"):
            om += 1
            line = ("$OMEGA 0 FIX" if eta0 else
                    "$OMEGA %s" % fmt(ext_final_val(final, "OMEGA(%d,%d)" % (om, om))))
        elif block == "SIGMA" and line.startswith("$SIGMA"):
            sg += 1
            fix = " FIX" if "FIX" in line else ""
            line = "$SIGMA %s%s" % (fmt(ext_final_val(final, "SIGMA(%d,%d)" % (sg, sg))), fix)
        out.append(line)
    s = "\n".join(out) + "\n"
    s = re.sub(r"MAXEVAL=\d+", "MAXEVAL=0 POSTHOC", s)
    return s


def ext_final_val(final, key):
    return final[key]


for n, cfg in FIXTURES.items():
    base = "reset_clock_%s" % n
    src = open(base + ".ctl").read()
    final = ext_final(base)
    header = ("; GENERATED by make_reset_clock_arms.py from %s.ctl at the final row of\n"
              "; results/%s.ext (NONMEM's optimum). MAXEVAL=0: one evaluation at that point.\n"
              % (base, base))
    arms = [("shifted", base + "_shifted.csv", False), ("control", base + ".csv", True)]
    if cfg["eta0"]:
        arms.insert(0, ("eval", base + ".csv", False))
    for arm, data, zero in arms:
        s = rewrite(src, final, cfg["time_theta"], zero, cfg["eta0"])
        s = s.replace("(written)", "(%s)" % arm, 1)
        if cfg["eta0"]:
            s = s.replace("(%s)" % arm, "(%s, eta = 0)" % arm, 1)
        s = s.replace("$DATA %s.csv" % base, "$DATA %s" % data)
        s = s.replace("FILE=%s.tab" % base, "FILE=%s_%s.tab" % (base, arm))
        s = s.replace("$INPUT", header + "$INPUT", 1)
        open("%s_%s.ctl" % (base, arm), "w").write(s)

"""Datasets and control streams for the #2656 anchor: `iiv_on_ruv` next to a dense `R`.

Writes, next to this script:

- `pair.csv`, a total (FREE = 0) / unbound (FREE = 1) pair per sample sharing an `L2`
  id, for the `block_sigma` twin;
- `triple.csv`, three rows per block at t, t + 0.5, t + 1 (`VIS` 1-3, `L2` = `BLK`), for
  the `correlation` twins;
- one `MAXEVAL=0` control stream per probe in `PROBES`, and one estimation per
  entry of `ESTIMATIONS`.

One-compartment IV, 30 subjects, two doses so later samples land on residual drug. The
per-subject residual SD factor exp(eta_ruv) has variance 0.25 (a factor of 0.6 to 1.6
across one SD each way), so eta_hat on the residual is far from 0 for many subjects.
The anchor compares two engines scoring the same data, so the generator is stdlib and
need not reproduce either engine's random stream.
"""

import csv
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
N_SUBJ = 30
CL, V, OM_CL, OM_V, OM_RUV = 1.0, 10.0, 0.09, 0.04, 0.25
DOSES = [0.0, 24.0]
BLOCK_STARTS = [1.0, 4.0, 10.0, 25.0, 30.0, 40.0]
HEADER = ["ID", "TIME", "DV", "EVID", "AMT", "CMT", "MDV", "FREE", "BLK", "VIS", "L2"]


def conc(t, cl, v):
    return sum(100.0 / v * math.exp(-cl / v * (t - td)) for td in DOSES if t >= td)


def subject_parameters(rng):
    cl = CL * math.exp(rng.gauss(0, math.sqrt(OM_CL)))
    v = V * math.exp(rng.gauss(0, math.sqrt(OM_V)))
    return cl, v, math.exp(rng.gauss(0, math.sqrt(OM_RUV)))


def dose_rows(i):
    return [[i, td, 0, 1, 100, 1, 1, 0, 0, 0, 0] for td in DOSES]


def write(name, rows):
    rows.sort(key=lambda r: (r[0], r[1], r[3] == 0, r[9]))
    with open(os.path.join(HERE, name), "w", newline="") as f:
        out = csv.writer(f)
        out.writerow(HEADER)
        out.writerows(rows)


def pair_rows():
    """Sigmas 0.12 / 0.20 correlated 0.6 across the pair."""
    rng = random.Random(2656)
    rows = []
    for i in range(1, N_SUBJ + 1):
        cl, v, scale = subject_parameters(rng)
        rows += dose_rows(i)
        for b, t in enumerate(BLOCK_STARTS, start=1):
            f = conc(t, cl, v)
            z1, z2 = rng.gauss(0, 1), rng.gauss(0, 1)
            e_tot = 0.12 * z1
            e_unb = 0.20 * (0.6 * z1 + 0.8 * z2)
            rows.append([i, t, round(f * (1 + scale * e_tot), 6), 0, 0, 1, 0, 0, b, 1, b])
            rows.append([i, t, round(f * (1 + scale * e_unb), 6), 0, 0, 1, 0, 1, b, 2, b])
    return rows


def triple_rows():
    """Proportional sigma 0.15, rows of a block compound-symmetric at rho = 0.5."""
    rng = random.Random(26560)
    rows = []
    for i in range(1, N_SUBJ + 1):
        cl, v, scale = subject_parameters(rng)
        rows += dose_rows(i)
        for b, start in enumerate(BLOCK_STARTS, start=1):
            shared = rng.gauss(0, 1)
            for vis in (1, 2, 3):
                t = start + 0.5 * (vis - 1)
                z = math.sqrt(0.5) * shared + math.sqrt(0.5) * rng.gauss(0, 1)
                y = conc(t, cl, v) * (1 + scale * 0.15 * z)
                rows.append([i, t, round(y, 6), 0, 0, 1, 0, 0, b, vis, b])
    return rows


HEAD = """$PROBLEM ferx #2656 iiv_on_ruv with a dense R: {title}
; Generated by make_data.py. Y = F + F*EXP(ETA(3))*(...): ETA(3) scales every residual SD
; of the subject, so R_i(eta) = exp(2*ETA(3)) * R_i(0).
$INPUT ID TIME DV EVID AMT CMT MDV FREE BLK VIS L2
$DATA {data} IGNORE=@
$SUBROUTINES ADVAN1 TRANS2
$PK
  CL = THETA(1)*EXP(ETA(1))
  V  = THETA(2)*EXP(ETA(2))
  S1 = V
$ERROR
  IPRED = F
"""
TAIL = """$OMEGA 0.08 FIX
$OMEGA 0.05 FIX
$OMEGA {om_ruv} FIX
{sigma}
$ESTIMATION METHOD=1 INTER MAXEVAL=0 POSTHOC NOABORT
$TABLE ID TIME ETA1 ETA2 ETA3 FIRSTONLY NOAPPEND NOPRINT ONEHEADER
       FORMAT=s1PE23.16 FILE={probe}.tab
$TABLE ID TIME DV MDV IPRED CWRES NPDE ESAMPLE=2000 SEED=2656 WRESCHOL
       NOAPPEND NOPRINT ONEHEADER FORMAT=s1PE23.16 FILE={probe}.res
"""
EST_TAIL = """$OMEGA 0.1
$OMEGA 0.1
$OMEGA 0.1
{sigma}
$ESTIMATION METHOD=1 INTER MAXEVAL=9999 NSIG=3 SIGL=9 PRINT=5 NOABORT
"""

BLOCK_ERROR = """  RES = (1 - FREE)*EPS(1) + FREE*EPS(2)
  Y = F + F*EXP(ETA(3))*RES
$THETA 1.05 FIX
$THETA 9.5 FIX
"""

# Lower Cholesky factor of a 3x3 correlation matrix, closed form per row.
SERIAL_ERROR = """  RHO = THETA(3)
{factor}
  RES = C1*EPS(1) + C2*EPS(2) + C3*EPS(3)
  Y = F + F*EXP(ETA(3))*THETA(4)*RES
$THETA 1.05 FIX
$THETA 9.5 FIX
$THETA (-0.9, {rho}, 0.99) FIX
$THETA 0.16 FIX
"""
CS_FACTOR = """  B = SQRT(1 - RHO*RHO)
  GM = RHO*(1 - RHO)/B
  DL = SQRT(1 - RHO*RHO - GM*GM)
  C1 = 1
  C2 = 0
  C3 = 0
  IF (VIS.EQ.2) THEN
    C1 = RHO
    C2 = B
  ENDIF
  IF (VIS.EQ.3) THEN
    C1 = RHO
    C2 = GM
    C3 = DL
  ENDIF"""
AR1_FACTOR = """  B = SQRT(1 - RHO*RHO)
  C1 = 1
  C2 = 0
  C3 = 0
  IF (VIS.EQ.2) THEN
    C1 = RHO
    C2 = B
  ENDIF
  IF (VIS.EQ.3) THEN
    C1 = RHO*RHO
    C2 = RHO*B
    C3 = B
  ENDIF"""
SERIAL_SIGMA = "$SIGMA 1 FIX\n$SIGMA 1 FIX\n$SIGMA 1 FIX"


def block_sigma_record(s1, s2, rho):
    return f"$SIGMA BLOCK(2) FIX {s1 * s1!r} {rho * s1 * s2!r} {s2 * s2!r}"


# (probe, title, data, error block, omega_ruv, sigma record)
PROBES = [
    ("bs_p06", "block_sigma rho=0.6", "pair.csv", BLOCK_ERROR, 0.25,
     block_sigma_record(0.12, 0.20, 0.6)),
    ("bs_m04", "block_sigma rho=-0.4", "pair.csv", BLOCK_ERROR, 0.25,
     block_sigma_record(0.12, 0.20, -0.4)),
    ("bs_lo", "block_sigma rho=0.6, small omega_ruv", "pair.csv", BLOCK_ERROR, 0.05,
     block_sigma_record(0.12, 0.20, 0.6)),
    ("cs_p05", "correlation cs rho=0.5", "triple.csv",
     SERIAL_ERROR.format(factor=CS_FACTOR, rho=0.5), 0.25, SERIAL_SIGMA),
    ("cs_m02", "correlation cs rho=-0.2", "triple.csv",
     SERIAL_ERROR.format(factor=CS_FACTOR, rho=-0.2), 0.25, SERIAL_SIGMA),
    ("ar1_p06", "correlation ar1 rho=0.6", "triple.csv",
     SERIAL_ERROR.format(factor=AR1_FACTOR, rho=0.6), 0.25, SERIAL_SIGMA),
    ("ar1_m04", "correlation ar1 rho=-0.4", "triple.csv",
     SERIAL_ERROR.format(factor=AR1_FACTOR, rho=-0.4), 0.25, SERIAL_SIGMA),
]


# Full FOCEI estimations from deliberately off-truth starts: every population parameter free.
BLOCK_EST = """  RES = (1 - FREE)*EPS(1) + FREE*EPS(2)
  Y = F + F*EXP(ETA(3))*RES
$THETA (0.1, 1.2, 10)
$THETA (1, 12, 100)
"""
CS_EST = """  RHO = THETA(3)
{factor}
  RES = C1*EPS(1) + C2*EPS(2) + C3*EPS(3)
  Y = F + F*EXP(ETA(3))*THETA(4)*RES
$THETA (0.1, 1.2, 10)
$THETA (1, 12, 100)
$THETA (-0.4, 0.3, 0.95)
$THETA (0.01, 0.2, 2)
""".format(factor=CS_FACTOR)
ESTIMATIONS = [
    ("bs_est", "block_sigma estimation", "pair.csv", BLOCK_EST,
     "$SIGMA BLOCK(2) 0.02 0.005 0.03"),
    ("cs_est", "correlation cs estimation", "triple.csv", CS_EST, SERIAL_SIGMA),
]


def main():
    write("pair.csv", pair_rows())
    write("triple.csv", triple_rows())
    for probe, title, data, error, om_ruv, sigma in PROBES:
        text = HEAD.format(title=title, data=data) + error
        text += TAIL.format(om_ruv=om_ruv, sigma=sigma, probe=probe)
        with open(os.path.join(HERE, f"{probe}.ctl"), "w") as f:
            f.write(text)
    for probe, title, data, error, sigma in ESTIMATIONS:
        text = HEAD.format(title=title, data=data) + error + EST_TAIL.format(sigma=sigma)
        with open(os.path.join(HERE, f"{probe}.ctl"), "w") as f:
            f.write(text)


if __name__ == "__main__":
    main()

using Copulas, Distributions, Printf
# repr gives the shortest decimal that round-trips, always with a `.` or an exponent.
f(x) = repr(Float64(x))
v(u) = "[" * join(f.(u), ", ") * "]"
pts2 = [[0.3,0.6],[0.05,0.9],[0.8,0.85],[0.5,0.5],[0.97,0.02]]
pts3 = [[0.3,0.6,0.8],[0.1,0.2,0.95],[0.7,0.7,0.7]]
pts4 = [[0.3,0.6,0.8,0.15],[0.55,0.45,0.9,0.6]]
cases = [
 ("Clayton", (d,θ)->ClaytonCopula(d,θ), [0.5,2.0,7.0]),
 ("Frank",   (d,θ)->FrankCopula(d,θ),   [0.7,3.0,12.0]),
 ("Gumbel",  (d,θ)->GumbelCopula(d,θ),  [1.2,1.7,4.0]),
 ("Joe",     (d,θ)->JoeCopula(d,θ),     [1.3,2.2,5.0]),
 ("Amh",     (d,θ)->AMHCopula(d,θ),     [0.2,0.6,0.9]),
]
# Two-parameter and the remaining one-parameter Archimedean families: (name, ctor taking
# (d, params...), parameter vectors, the dimensions each vector is valid in).
cases2 = [
 ("InvGaussian",   (d,p)->InvGaussianCopula(d,p...),   [[0.3],[1.5],[6.0]], [2,3,4]),
 ("GumbelBarnett", (d,p)->GumbelBarnettCopula(d,p...), [[0.1],[0.2]],       [2,3,4]),
 ("GumbelBarnett", (d,p)->GumbelBarnettCopula(d,p...), [[0.8]],             [2]),
 ("Bb1",  (d,p)->BB1Copula(d,p...),  [[0.5,1.5],[2.0,1.2],[0.8,3.0]], [2,3,4]),
 ("Bb2",  (d,p)->BB2Copula(d,p...),  [[0.5,1.5],[2.0,0.4],[1.0,3.0]], [2,3,4]),
 ("Bb3",  (d,p)->BB3Copula(d,p...),  [[1.3,0.5],[2.0,2.0],[3.0,0.2]], [2,3,4]),
 ("Bb6",  (d,p)->BB6Copula(d,p...),  [[1.2,1.3],[2.0,1.1],[1.5,2.5]], [2,3,4]),
 ("Bb7",  (d,p)->BB7Copula(d,p...),  [[1.3,0.5],[2.0,2.0],[3.0,0.2]], [2,3,4]),
 ("Bb8",  (d,p)->BB8Copula(d,p...),  [[1.5,0.5],[3.0,0.9],[1.2,0.2]], [2,3,4]),
 ("Bb9",  (d,p)->BB9Copula(d,p...),  [[1.3,0.5],[2.0,2.0],[3.0,0.2]], [2,3,4]),
 ("Bb10", (d,p)->BB10Copula(d,p...), [[0.5,0.3],[2.0,0.8],[1.0,0.1]], [2,3,4]),
 # Extreme value: Copulas.jl's LogCopula is the Gumbel (ferx's `logistic` alias).
 ("Gumbel",       (d,p)->LogCopula(d,p...),        [[1.4],[3.0]], [2,3,4]),
 ("Galambos",     (d,p)->GalambosCopula(d,p...),   [[0.4],[1.5],[4.0]], [2,3,4]),
 ("HuslerReiss",  (d,p)->HuslerReissCopula(d,p...), [[0.5],[1.5],[4.0]], [2]),
 ("TEv",          (d,p)->tEVCopula(d,p...),        [[4.0,0.3],[1.5,-0.4],[10.0,0.8]], [2]),
 ("Mixed",        (d,p)->MixedCopula(d,p...),      [[0.3],[0.9]], [2,3,4]),
 ("AsymMixed",    (d,p)->AsymMixedCopula(d,p...),  [[0.4,0.1],[0.6,-0.1],[0.2,0.3]], [2]),
 ("AsymLog",      (d,p)->AsymLogCopula(d,p...),    [[2.0,0.5,0.8],[4.0,0.9,0.3],[1.5,1.0,1.0]], [2]),
 ("AsymGalambos", (d,p)->AsymGalambosCopula(d,p...), [[0.8,0.5,0.8],[2.5,0.9,0.3],[1.0,1.0,1.0]], [2]),
 # Archimax: Clayton (BB4) / Gumbel (BB5) generator over a Galambos tail.
 ("Bb4",          (d,p)->BB4Copula(d,p...),        [[0.8,1.2],[2.0,0.5]], [2]),
 ("Bb5",          (d,p)->BB5Copula(d,p...),        [[1.5,1.2],[2.5,0.4]], [2]),
]
println("// Generated by copula_anchor/refs.jl with Copulas.jl ", pkgversion(Copulas))
println("const ARCH_REFS: &[(CopulaFamily, f64, &[f64], f64, f64)] = &[")
for (name, mk, θs) in cases, θ in θs, pts in (pts2, pts3, pts4), u in pts
    C = mk(length(u), θ)
    println("    (CopulaFamily::$name, $(f(θ)), &$(v(u)), $(f(logpdf(C, u))), $(f(cdf(C, u)))),")
end
println("];")
println("const ARCH2_REFS: &[(CopulaFamily, &[f64], &[f64], f64, f64)] = &[")
for (name, mk, ps, dims) in cases2, pv in ps, pts in (pts2, pts3, pts4), u in pts
    length(u) in dims || continue
    C = mk(length(u), pv)
    println("    (CopulaFamily::$name, &$(v(pv)), &$(v(u)), $(f(logpdf(C, u))), $(f(cdf(C, u)))),")
end
println("];")
println("const TAU2_REFS: &[(CopulaFamily, &[f64], f64)] = &[")
for (name, mk, ps, dims) in cases2, pv in ps
    println("    (CopulaFamily::$name, &$(v(pv)), $(f(Copulas.τ(mk(2, pv))))),")
end
println("];")
# Frank and AMH negative, d = 2 only
println("const ARCH_NEG_REFS: &[(CopulaFamily, f64, &[f64], f64, f64)] = &[")
for (name, mk, θs) in (("Frank", (d,θ)->FrankCopula(d,θ), [-4.0,-0.5]), ("Amh", (d,θ)->AMHCopula(d,θ), [-0.7,-0.2])), θ in θs, u in pts2
    C = mk(2, θ)
    println("    (CopulaFamily::$name, $(f(θ)), &$(v(u)), $(f(logpdf(C, u))), $(f(cdf(C, u)))),")
end
println("];")
println("const TAU_REFS: &[(CopulaFamily, f64, f64)] = &[")
for (name, mk, θs) in cases, θ in θs
    println("    (CopulaFamily::$name, $(f(θ)), $(f(Copulas.τ(mk(2, θ))))),")
end
println("];")
# t copula: (nu, R lower tri row-major, u, logpdf)
println("const T_REFS: &[(f64, &[f64], &[f64], f64)] = &[")
for (ν, R) in ((4.0, [1.0 0.5; 0.5 1.0]), (12.0, [1.0 -0.3; -0.3 1.0]), (3.0, [1.0 0.4 0.2; 0.4 1.0 -0.1; 0.2 -0.1 1.0])), u in (size(R,1)==2 ? pts2 : pts3)
    C = TCopula(ν, R)
    tri = [R[i,j] for i in 1:size(R,1) for j in 1:i]
    println("    ($(f(ν)), &$(v(tri)), &$(v(u)), $(f(logpdf(C, u)))),")
end
println("];")
# Constructions over families, and FGM / Plackett: (label, parameters in ferx's order, u,
# logpdf, cdf). The labels are mapped to ferx's `CopulaSpec` in
# src/stats/eta_density_copula_tests.rs (`composite_spec`).
comps = [
 ("fgm2",            [0.6],                         p -> FGMCopula(2, p[1])),
 ("fgm3",            [0.3, -0.2, 0.25, 0.1],        p -> FGMCopula(3, p)),
 ("plackett",        [3.5],                         p -> PlackettCopula(p[1])),
 ("plackett_neg",    [0.3],                         p -> PlackettCopula(p[1])),
 ("survival_clayton3", [1.8],                       p -> SurvivalCopula(ClaytonCopula(3, p[1]))),
 ("survival_clayton3_flip2", [1.8],                 p -> SurvivalCopula(ClaytonCopula(3, p[1]), (2,))),
 ("rot90_gumbel",    [1.7],                         p -> Rotated90Copula(GumbelCopula(2, p[1]))),
 ("rot270_gumbel",   [1.7],                         p -> Rotated270Copula(GumbelCopula(2, p[1]))),
 ("khoudraji_gumbel", [2.5, 0.3, 0.8],              p -> KhoudrajiCopula(2, GumbelCopula(2, p[1]), [p[2], p[3]])),
 ("khoudraji_clayton_gumbel", [1.5, 2.0, 0.4, 0.7], p -> KhoudrajiCopula(2, (ClaytonCopula(2, p[1]), GumbelCopula(2, p[2])), [p[3], p[4]])),
 # weights rows 2 and 3 (ferx's rows 1..K); row 1 = 1 − their column sums.
 ("liebscher3", [1.2, 1.8, 4.0, 0.3, 0.2, 0.25, 0.5],
     p -> LiebscherCopula(2, (ClaytonCopula(2, p[1]), GumbelCopula(2, p[2]), FrankCopula(2, p[3])),
                          [1 - p[4] - p[6]  1 - p[5] - p[7]; p[4] p[5]; p[6] p[7]])),
 # root Clayton θ₀ over (a nested Clayton θ₁ on coordinates 1, 2) and the leaf 3.
 ("nested_clayton", [0.8, 2.5],
     p -> NestedArchimedeanCopula(Copulas.ClaytonGenerator(p[1]); leaves = [3], children = [ClaytonCopula(2, p[2]) => [1, 2]])),
]
println("const COMPOSITE_REFS: &[(&str, &[f64], &[f64], f64, f64)] = &[")
for (label, pv, mk) in comps
    C = mk(pv)
    for u in (length(C) == 2 ? pts2 : pts3)
        println("    (\"$label\", &$(v(pv)), &$(v(u)), $(f(logpdf(C, u))), $(f(cdf(C, u)))),")
    end
end
println("];")

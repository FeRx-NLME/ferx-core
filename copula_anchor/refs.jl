using Copulas, Distributions, Printf
# repr gives the shortest decimal that round-trips, always with a `.` or an exponent.
f(x) = repr(Float64(x))
v(u) = "[" * join(f.(u), ", ") * "]"
pts2 = [[0.3,0.6],[0.05,0.9],[0.8,0.85],[0.5,0.5],[0.97,0.02]]
pts3 = [[0.3,0.6,0.8],[0.1,0.2,0.95],[0.7,0.7,0.7]]
pts4 = [[0.3,0.6,0.8,0.15],[0.55,0.45,0.9,0.6]]
cases = [
 ("Clayton", (d,θ)->ClaytonCopula(d,θ), [0.5,2.0,7.0]),
 ("Frank",   (d,θ)->FrankCopula(d,θ),   [0.7,3.0,12.0]),
 ("Gumbel",  (d,θ)->GumbelCopula(d,θ),  [1.2,1.7,4.0]),
 ("Joe",     (d,θ)->JoeCopula(d,θ),     [1.3,2.2,5.0]),
 ("Amh",     (d,θ)->AMHCopula(d,θ),     [0.2,0.6,0.9]),
]
# Two-parameter and the remaining one-parameter Archimedean families: (name, ctor taking
# (d, params...), parameter vectors, the dimensions each vector is valid in).
cases2 = [
 ("InvGaussian",   (d,p)->InvGaussianCopula(d,p...),   [[0.3],[1.5],[6.0]], [2,3,4]),
 ("GumbelBarnett", (d,p)->GumbelBarnettCopula(d,p...), [[0.1],[0.2]],       [2,3,4]),
 ("GumbelBarnett", (d,p)->GumbelBarnettCopula(d,p...), [[0.8]],             [2]),
 ("Bb1",  (d,p)->BB1Copula(d,p...),  [[0.5,1.5],[2.0,1.2],[0.8,3.0]], [2,3,4]),
 ("Bb2",  (d,p)->BB2Copula(d,p...),  [[0.5,1.5],[2.0,0.4],[1.0,3.0]], [2,3,4]),
 ("Bb3",  (d,p)->BB3Copula(d,p...),  [[1.3,0.5],[2.0,2.0],[3.0,0.2]], [2,3,4]),
 ("Bb6",  (d,p)->BB6Copula(d,p...),  [[1.2,1.3],[2.0,1.1],[1.5,2.5]], [2,3,4]),
 ("Bb7",  (d,p)->BB7Copula(d,p...),  [[1.3,0.5],[2.0,2.0],[3.0,0.2]], [2,3,4]),
 ("Bb8",  (d,p)->BB8Copula(d,p...),  [[1.5,0.5],[3.0,0.9],[1.2,0.2]], [2,3,4]),
 ("Bb9",  (d,p)->BB9Copula(d,p...),  [[1.3,0.5],[2.0,2.0],[3.0,0.2]], [2,3,4]),
 ("Bb10", (d,p)->BB10Copula(d,p...), [[0.5,0.3],[2.0,0.8],[1.0,0.1]], [2,3,4]),
 # Extreme value: Copulas.jl's LogCopula is the Gumbel (ferx's `logistic` alias).
 ("Gumbel",       (d,p)->LogCopula(d,p...),        [[1.4],[3.0]], [2,3,4]),
 ("Galambos",     (d,p)->GalambosCopula(d,p...),   [[0.4],[1.5],[4.0]], [2,3,4]),
 ("HuslerReiss",  (d,p)->HuslerReissCopula(d,p...), [[0.5],[1.5],[4.0]], [2]),
 ("TEv",          (d,p)->tEVCopula(d,p...),        [[4.0,0.3],[1.5,-0.4],[10.0,0.8]], [2]),
 ("Mixed",        (d,p)->MixedCopula(d,p...),      [[0.3],[0.9]], [2,3,4]),
 ("AsymMixed",    (d,p)->AsymMixedCopula(d,p...),  [[0.4,0.1],[0.6,-0.1],[0.2,0.3]], [2]),
 ("AsymLog",      (d,p)->AsymLogCopula(d,p...),    [[2.0,0.5,0.8],[4.0,0.9,0.3],[1.5,1.0,1.0]], [2]),
 ("AsymGalambos", (d,p)->AsymGalambosCopula(d,p...), [[0.8,0.5,0.8],[2.5,0.9,0.3],[1.0,1.0,1.0]], [2]),
 # Archimax: Clayton (BB4) / Gumbel (BB5) generator over a Galambos tail.
 ("Bb4",          (d,p)->BB4Copula(d,p...),        [[0.8,1.2],[2.0,0.5]], [2]),
 ("Bb5",          (d,p)->BB5Copula(d,p...),        [[1.5,1.2],[2.5,0.4]], [2]),

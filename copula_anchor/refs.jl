println("// Generated by copula_anchor/refs.jl with Copulas.jl ", pkgversion(Copulas))
println("const ARCH_REFS: &[(CopulaFamily, f64, &[f64], f64, f64)] = &[")
for (name, mk, θs) in cases, θ in θs, pts in (pts2, pts3, pts4), u in pts
    C = mk(length(u), θ)
    println("    (CopulaFamily::$name, $(f(θ)), &$(v(u)), $(f(logpdf(C, u))), $(f(cdf(C, u)))),")
end
println("];")
println("const ARCH2_REFS: &[(CopulaFamily, &[f64], &[f64], f64, f64)] = &[")
for (name, mk, ps, dims) in cases2, pv in ps, pts in (pts2, pts3, pts4), u in pts
    length(u) in dims || continue
    C = mk(length(u), pv)
    println("    (CopulaFamily::$name, &$(v(pv)), &$(v(u)), $(f(logpdf(C, u))), $(f(cdf(C, u)))),")
end
println("];")
println("const TAU2_REFS: &[(CopulaFamily, &[f64], f64)] = &[")
for (name, mk, ps, dims) in cases2, pv in ps
    println("    (CopulaFamily::$name, &$(v(pv)), $(f(Copulas.τ(mk(2, pv))))),")
end
println("];")
# Frank and AMH negative, d = 2 only
println("const ARCH_NEG_REFS: &[(CopulaFamily, f64, &[f64], f64, f64)] = &[")
for (name, mk, θs) in (("Frank", (d,θ)->FrankCopula(d,θ), [-4.0,-0.5]), ("Amh", (d,θ)->AMHCopula(d,θ), [-0.7,-0.2])), θ in θs, u in pts2
    C = mk(2, θ)
    println("    (CopulaFamily::$name, $(f(θ)), &$(v(u)), $(f(logpdf(C, u))), $(f(cdf(C, u)))),")
end
println("];")
println("const TAU_REFS: &[(CopulaFamily, f64, f64)] = &[")
for (name, mk, θs) in cases, θ in θs
    println("    (CopulaFamily::$name, $(f(θ)), $(f(Copulas.τ(mk(2, θ))))),")
end
println("];")
# t copula: (nu, R lower tri row-major, u, logpdf)
println("const T_REFS: &[(f64, &[f64], &[f64], f64)] = &[")
for (ν, R) in ((4.0, [1.0 0.5; 0.5 1.0]), (12.0, [1.0 -0.3; -0.3 1.0]), (3.0, [1.0 0.4 0.2; 0.4 1.0 -0.1; 0.2 -0.1 1.0])), u in (size(R,1)==2 ? pts2 : pts3)
    C = TCopula(ν, R)
    tri = [R[i,j] for i in 1:size(R,1) for j in 1:i]
    println("    ($(f(ν)), &$(v(tri)), &$(v(u)), $(f(logpdf(C, u)))),")
end
println("];")

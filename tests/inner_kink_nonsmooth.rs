//! #3159 end to end: on an `[odes]` model whose observation is clipped at a threshold, with
//! `inner_kick = true`, the returned EBE of every subject is the minimum of its individual
//! objective.
//!
//! The fixture is a one-state decay restarted at each occasion, observed through
//! `max(0, eff − TH)` with IIV and IOV on `TH` (`tests/fixtures/clipped_decay`). Six of its
//! subjects: 14 and 17 on whom the objective-stall stop certified a point on a kink's valley
//! floor at ‖g‖ ≈ 7 and 10, 0.175 and 0.055 above the minimum; 20 and 27 whose descent ended in
//! a second local mode 0.011 away, 0.165 and 0.032 above it; and 1 and 2 as controls. The kicks
//! are opt-in, under `inner_kick` (#3159); the stall escape runs by default here, because the
//! clipped readout is a branch on a state and an η, which the parser flags (#3210).
//!
//! The reference is an independent Nelder–Mead minimum of the same objective written out in
//! Python (`sum (DV − max(0, BASE·e^{−K·tad} − TH))²/σ² + ηᵀΩ⁻¹η + Σ κ²/ω_κ`), regenerated by
//! `python3 tests/fixtures/clipped_decay/oracle.py tests/fixtures/clipped_decay/clipped.csv`
//! (no dependencies; it reproduces [`ORACLE`] within 7e-6). Worst of the six, measured: 1.8e-4
//! under the dense driver (subject 27), bound 1e-3; 3.2e-3 under L-BFGS (subject 17), bound 5e-3,
//! whose limited-memory metric resolves the shallow, prior-constrained direction along
//! `ETA_TH`/`KAPPA_1`/`KAPPA_2` less exactly — ten times the escapes or iterations reaches the
//! same point, so it is not short of either.
//!
//! Mutations (run): the stall escape off in the dense driver → subject 17 fails (14 is then
//! reached by the kicks), and in the L-BFGS driver → the same under `lbfgs`; the kick restarts off
//! (the default) → subject 20 fails (27 too). On `main` all four fail. The kink flag forced off
//! (#3210) → the default-escape tests fail (subjects 14 and 17 under `bfgs`, 17 under `lbfgs`,
//! subject 40 of the non-IOV cut); the flag turning the kicks on → subject 20's negative fails.

use std::path::Path;

/// `[ETA_BASE, ETA_TH, KAPPA_1, KAPPA_2]` of each subject's minimum.
const ORACLE: [(&str, [f64; 4]); 6] = [
    ("1", [-0.081773, 0.092269, 0.480459, -0.43945]),
    ("2", [-0.217644, -0.201366, 0.072804, -0.162301]),
    ("14", [0.302834, 0.29221, -0.37159, 0.501461]),
    ("17", [-0.237811, 0.535079, 0.118906, 0.118906]),
    ("20", [-0.283402, 0.141441, 0.435102, -0.372239]),
    ("27", [-0.096806, -0.356722, -0.051522, -0.107021]),
];

/// The fixture's fit under `driver` (`bfgs` forces the dense driver, `lbfgs` the limited-memory
/// one: the fixture has 4 coordinates, below the default switch at 32), plus `extra` options.
fn fit_with(driver: &str, extra: &str) -> ferx_core::FitResult {
    fit_src(|model| model, |csv| csv, driver, extra)
}

/// [`fit_with`] on the fixture's model and data as `model` and `data` rewrite them.
fn fit_src(
    model: impl Fn(String) -> String, data: impl Fn(String) -> String, driver: &str, extra: &str,
) -> ferx_core::FitResult {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/clipped_decay");
    let read = |f: &str| std::fs::read_to_string(dir.join(f)).unwrap();
    let tmp = tempfile::tempdir().unwrap();
    let (path, csv) = (tmp.path().join("clipped.ferx"), tmp.path().join("clipped.csv"));
    // One thread: the EBE solves are independent of each other, but a parallel run's rayon
    // worker count is free to change, and the oracle comparison wants one fixed path.
    let src = model(read("clipped.ferx"));
    std::fs::write(&path, format!("{src}  inner_optimizer = {driver}\n  threads = 1\n{extra}"))
        .unwrap();
    std::fs::write(&csv, data(read("clipped.csv"))).unwrap();
    ferx_core::run_model_with_data(path.to_str().unwrap(), Some(csv.to_str().unwrap()))
        .expect("fit")
        .0
}

/// How far each subject's EBE is from its [`ORACLE`] minimum, by id.
fn distances(fit: &ferx_core::FitResult) -> Vec<(&'static str, f64)> {
    ORACLE
        .iter()
        .map(|&(id, want)| {
            let i = fit.subjects.iter().position(|s| s.id == id).unwrap_or_else(|| panic!("{id}"));
            let (eta, kappas) = (&fit.subjects[i].eta, &fit.ebe_kappas[i]);
            let got = [eta[0], eta[1], kappas[0][0], kappas[1][0]];
            let worst = got.iter().zip(want).map(|(g, w)| (g - w).abs()).fold(0.0, f64::max); // nan-ok: asserted below
            assert!(worst.is_finite(), "subject {id}: EBE {got:?}");
            (id, worst)
        })
        .collect()
}

fn check(driver: &str, bound: f64) {
    for (id, worst) in distances(&fit_with(driver, "  inner_kick = true\n")) {
        assert!(worst < bound, "{driver}, subject {id}: EBE is {worst:.1e} from its minimum");
    }
}

#[test]
fn a_clipped_models_ebes_are_the_minima_of_their_individual_objectives() {
    check("bfgs", 1e-3);
}

/// The same fixture on the L-BFGS driver, which has its own copy of the stall exit.
#[test]
fn a_clipped_models_ebes_are_the_minima_under_the_limited_memory_driver() {
    check("lbfgs", 5e-3);
}

/// Without IOV (`find_ebe_solve`'s kicks, not the IOV solve's): occasion 1 only, `TH` on IIV
/// alone. Subject 20 has a second mode there too. Its minimum (`oracle.py clipped.csv occ1`) is
/// `[-0.292328, 0.568448]`; the default ends at `[-0.2724, 0.6029]`, and the kicks reach it.
#[test]
fn without_iov_the_kicks_reach_a_second_mode() {
    let model = |m: String| {
        m.replace("  kappa KAPPA_TH ~ 0.04\n", "")
            .replace(" + KAPPA_TH", "")
            .replace("  iov_column = OCC\n", "")
    };
    let occ1 =
        |d: String| d.lines().filter(|l| !l.ends_with(",2")).map(|l| l.to_owned() + "\n").collect();
    let eta20 = |extra| {
        let fit = fit_src(model, occ1, "bfgs", extra);
        let s = fit.subjects.iter().find(|s| s.id == "20").expect("subject 20");
        ((s.eta[0] + 0.292328).abs()).max((s.eta[1] - 0.568448).abs())
    };
    assert!(eta20("") > 1e-2, "premise: the default leaves the second mode unreached");
    assert!(eta20("  inner_kick = true\n") < 1e-4);
}

/// Under the default the stall escape runs on this model (#3210: the clipped readout is a kink
/// the parser flags), so 14 and 17 leave their valley floors; the kicks stay opt-in, so subject
/// 20's second mode, 0.011 away and 0.165 lower, is still not reached without `inner_kick` (a
/// differential pair with `inner_kick = true`, which reaches it). Measured (Linux, the same on
/// macOS): the worst of 1, 2, 14 and 17 is 7.6e-6 (14), bound 1e-4; with the flag forced off 14
/// and 17 end 5.4e-2 and 2.6e-2 away. Subject 20 is 7.8e-3 away either way.
#[test]
fn the_stall_escape_is_on_by_default_for_a_kinked_model_and_the_kicks_are_not() {
    let default = distances(&fit_with("bfgs", ""));
    for &(id, d) in &default {
        if id != "20" && id != "27" {
            assert!(d < 1e-4, "bfgs, subject {id}: the default left its stall ({d:.1e} off)");
        }
    }
    let d20 = default.iter().find(|&&(id, _)| id == "20").unwrap().1;
    assert!(d20 > 5e-3, "the kicks ran by default: subject 20 is {d20:.1e} from its minimum");
    let kicked = distances(&fit_with("bfgs", "  inner_kick = true\n"));
    assert!(kicked.iter().find(|&&(id, _)| id == "20").unwrap().1 < 5e-3);
}

/// The same under L-BFGS, whose stall exit is its own copy: there 17 stalls without the escape
/// (14 does not, and 20 reaches its minimum without the kicks). Measured (Linux): 3.2e-3 under
/// the default, as `a_clipped_models_ebes_are_the_minima_under_the_limited_memory_driver`'s bound
/// allows; 1.1e-2 with the flag forced off.
#[test]
fn the_stall_escape_is_on_by_default_under_the_limited_memory_driver() {
    let (_, d17) =
        distances(&fit_with("lbfgs", "")).into_iter().find(|&(id, _)| id == "17").unwrap();
    assert!(d17 < 5e-3, "lbfgs, subject 17: the default left its stall ({d17:.1e} off)");
}

/// The non-IOV solve (`find_ebe_solve`) runs the escape by default on a flagged model too. None
/// of the fixture's six subjects stalls without IOV, nor did any of the 40 of seed 41 under
/// either cut (occasion 1 alone, or both occasions with `TH` on IIV only): the only stall found
/// in 320 subjects (seeds 42-49) is subject 40 of seed 45, on occasion 1 under L-BFGS
/// (`stall_iiv.csv`, from `make_data.py stall_iiv.csv 45 150 0.15 40`). Every record of it is
/// clipped there, so its minimum (`oracle.py stall_iiv.csv occ1`) lies on the clip's boundary:
/// `[-0.274399, 0.617397]`. Measured (Linux): 1.1e-6 under the default, bound 1e-4; 4.3e-2 with
/// the flag forced off. Under the dense driver it reaches the minimum either way.
#[test]
fn the_non_iov_solve_runs_the_stall_escape_by_default_for_a_kinked_model() {
    let model = |m: String| {
        m.replace("  kappa KAPPA_TH ~ 0.04\n", "")
            .replace(" + KAPPA_TH", "")
            .replace("  iov_column = OCC\n", "")
    };
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/clipped_decay");
    let stall = std::fs::read_to_string(dir.join("stall_iiv.csv")).unwrap();
    let occ1 = |_: String| -> String {
        stall.lines().filter(|l| !l.ends_with(",2")).map(|l| l.to_owned() + "\n").collect()
    };
    let fit = fit_src(model, occ1, "lbfgs", "");
    let s = fit.subjects.iter().find(|s| s.id == "40").expect("subject 40");
    assert!(s.eta.iter().all(|e| e.is_finite()), "{:?}", s.eta);
    let d = ((s.eta[0] + 0.274399).abs()).max((s.eta[1] - 0.617397).abs()); // nan-ok: asserted above
    assert!(d < 1e-4, "subject 40: the default left its stall ({d:.1e} off)");
}

/// In a fit that estimates, the kicked EBEs are the ones reported (#3159 review): one outer
/// iteration kicked in every solve ends lower than the same iteration unkicked. Kicked in the
/// final pass only (#3202's first design), the search's unkicked EBEs won #833's comparison and
/// the fit ended above the unkicked one. A differential pair, so a shift of the outer path that
/// moves both fits (as #3153's `f / c` first leg did) cancels.
///
/// The second arm is the default, which on this model runs the stall escape but not the kicks
/// (#3210: the clipped readout is a flagged kink). Measured (Linux, the same on macOS): kicked
/// −4835.241380, default −4832.989357, final pass only −4832.390237, so the gaps to the default
/// are −2.252, and +0.599 for the final-pass mutant (which kills this test alone). Both fits
/// carry #833's warning: the kicked one on subject 17 (cold re-solve 8.51 worse), the default
/// on 2 subjects whose warm EBEs stayed in a higher mode (cold re-solve 0.599 lower). Before
/// #3210 the default (no escape) reached −4835.017384 and the gaps were 0.224 and −0.572.
#[test]
fn an_estimating_fit_reports_the_kicked_ebes() {
    let kicked = fit_with("bfgs", "  inner_kick = true\n  maxiter = 1\n");
    let unkicked = fit_with("bfgs", "  maxiter = 1\n");
    assert!(
        kicked.ofv < unkicked.ofv - 0.1,
        "kicked OFV {} vs unkicked {}: {:?}",
        kicked.ofv,
        unkicked.ofv,
        kicked.warnings
    );
}
